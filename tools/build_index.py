"""Write the firmware index: the README printer table and printers/<slug>.md.

The README table goes between the INDEX_START and INDEX_END markers. All other
README text is hand-written and stays as it is.

Usage:
    python tools/build_index.py           # read releases from GitHub, write files
    python tools/build_index.py --check   # exit 1 if the files are out of date
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from mirror import (  # noqa: E402
    MODELS,
    PACKAGE_TYPES,
    REPO_ROOT,
    ROLLBACK_LIMITS,
    GitHub,
    Tag,
    needs_rollback_warning,
    parse_asset_name,
)

INDEX_START = "<!-- index:start -->"
INDEX_END = "<!-- index:end -->"
_FF_DATE = re.compile(r"Released by FlashForge on (\d{4}-\d{2}-\d{2})")


def release_date(release: dict) -> str:
    """FlashForge's release date when the notes state it, else the mirror date."""
    m = _FF_DATE.search(release.get("body") or "")
    return m.group(1) if m else (release.get("published_at") or "")[:10]


def collect(releases: list[dict]) -> dict[str, list[tuple[Tag, dict]]]:
    """slug -> [(tag, release)], newest version first."""
    by_model: dict[str, list[tuple[Tag, dict]]] = {slug: [] for slug in MODELS}
    for rel in releases:
        tag = Tag.parse(rel.get("tag_name", ""))
        if tag and not rel.get("draft"):
            by_model[tag.slug].append((tag, rel))
    for items in by_model.values():
        items.sort(key=lambda item: item[0].sort_key(), reverse=True)
    return by_model


def usb_link(tag: Tag, rel: dict) -> str:
    asset = next((a for a in rel.get("assets", []) if a["name"] == tag.usb_name), None)
    if asset is None:
        return "_not built yet_"
    return f"[{tag.usb_name}]({asset['browser_download_url']})"


def raw_links(rel: dict) -> str:
    found = {}
    for asset in rel.get("assets", []):
        parsed = parse_asset_name(asset["name"])
        if parsed:
            found[parsed[0]] = f"[{parsed[0]} {parsed[1]}]({asset['browser_download_url']})"
    return " · ".join(found[p] for p in PACKAGE_TYPES if p in found) or "—"


def rollback_note(slug: str) -> list[str]:
    if slug not in ROLLBACK_LIMITS:
        return []
    limit = ".".join(str(n) for n in ROLLBACK_LIMITS[slug])
    return [
        "> [!WARNING]",
        f"> Firmware {limit} and later cannot be rolled back to 1.9.8 or earlier (FlashForge notice).",
        f"> Do not install an older file on a printer that has firmware {limit} or later.",
        "",
    ]


def model_page(slug: str, items: list[tuple[Tag, dict]]) -> str:
    model = MODELS[slug]
    lines = [
        f"# {model.name} firmware",
        "",
        "[All printers](../README.md) · [How to update with a USB drive](../README.md#update-with-a-usb-drive)",
        "",
        "<!-- This file is generated by tools/build_index.py. Do not edit it by hand. -->",
        "",
    ]
    if not items:
        return "\n".join(lines + ["No firmware is mirrored for this printer yet.", ""])
    tag, rel = items[0]
    lines += [
        f"**Latest: {tag.software}-{tag.control}** ({release_date(rel)}). "
        f"USB update file: {usb_link(tag, rel)}. [Release notes]({rel['html_url']})",
        "",
    ]
    lines += rollback_note(slug)
    lines += [
        "## All versions",
        "",
        "Version = software version - control version. Newest first.",
        "",
        "| Version | Released | USB update file | Raw packages (for developers) | Notes |",
        "|---|---|---|---|---|",
    ]
    for i, (tag, rel) in enumerate(items):
        label = f"**{tag.software}-{tag.control}** (latest)" if i == 0 else f"{tag.software}-{tag.control}"
        if needs_rollback_warning(tag):
            label += " ⚠️"
        lines.append(f"| {label} | {release_date(rel)} | {usb_link(tag, rel)} | "
                     f"{raw_links(rel)} | [Release]({rel['html_url']}) |")
    if any(needs_rollback_warning(t) for t, _ in items):
        lines += ["", "⚠️ = do not install on a printer that has firmware 2.0.0 or later."]
    return "\n".join(lines) + "\n"


def readme_table(by_model: dict[str, list[tuple[Tag, dict]]]) -> str:
    lines = [
        INDEX_START,
        "<!-- This table is generated by tools/build_index.py. Do not edit it by hand. -->",
        "",
        "| Printer | Latest firmware | Released | USB update file | All versions |",
        "|---|---|---|---|---|",
    ]
    for slug, model in MODELS.items():
        items = by_model.get(slug) or []
        page = f"[{model.name} versions](printers/{slug}.md)"
        if not items:
            lines.append(f"| {model.name} | — | — | — | {page} |")
            continue
        tag, rel = items[0]
        lines.append(f"| **{model.name}** | [{tag.software}-{tag.control}]({rel['html_url']}) | "
                     f"{release_date(rel)} | {usb_link(tag, rel)} | {page} |")
    lines.append(INDEX_END)
    return "\n".join(lines)


def render(releases: list[dict], readme: str) -> dict[Path, str]:
    """Return {path: new content} for every generated file."""
    by_model = collect(releases)
    if INDEX_START not in readme or INDEX_END not in readme:
        raise ValueError(f"README.md has no {INDEX_START} / {INDEX_END} markers")
    before, rest = readme.split(INDEX_START, 1)
    after = rest.split(INDEX_END, 1)[1]
    out = {REPO_ROOT / "README.md": before + readme_table(by_model) + after}
    for slug, items in by_model.items():
        out[REPO_ROOT / "printers" / f"{slug}.md"] = model_page(slug, items)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if a file would change")
    ap.add_argument("--repo", help="owner/name (default: $GITHUB_REPOSITORY or the mirror)")
    args = ap.parse_args(argv)

    readme_path = REPO_ROOT / "README.md"
    files = render(GitHub(args.repo).releases(), readme_path.read_text(encoding="utf-8"))
    changed = [p for p, text in files.items()
               if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in changed:
            print(f"out of date: {p.relative_to(REPO_ROOT)}")
        return 1 if changed else 0
    for p in changed:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
